const tables: Record<Locale, Readonly<Record<TextKey, string>>> = { pt, en };

let locale: Locale = 'pt';

export function setLocale(next: Locale): void {
  locale = next;
}

export function currentLocale(): Locale {
  return locale;
}

/** Looks up a text, falling back to Portuguese (and to the key), and fills `{placeholders}`. */
export function t(key: TextKey, params: Record<string, string | number> = {}): string {
  const template: string | undefined = tables[locale][key] ?? (pt as Record<string, string>)[key];
  if (template === undefined) return key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`));
}

export function hasText(key: string): key is TextKey {
  return key in pt;
}

export function roleName(role: RoleId): string {
  const key = `role.${role}`;
  return hasText(key) ? t(key) : (ROLES[role]?.name ?? role);
}

export function abilityName(id: AbilityId): string {
  return t(`ability.${id}` as TextKey);
}

export function placementError(error: string): string {
  const key = `place.err.${error}`;
  if (hasText(key)) return t(key);
  const generic = `err.${error}`;
  return hasText(generic) ? t(generic) : t('err.generic');
}

